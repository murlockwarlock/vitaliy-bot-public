def main():
    conn = sqlite3.connect(DB_PATH)
    cur = conn.cursor()
    for key, text in UPDATES.items():
        cur.execute("SELECT text_content FROM content WHERE key = ?", (key,))
        row = cur.fetchone()
        if row is not None:
            if not row[0]:
                cur.execute("UPDATE content SET text_content = ? WHERE key = ?", (text, key))
                print(f"  ~ Updated empty content: {key}")
            else:
                print(f"  - Preserved existing content: {key}")
        else:
            cur.execute("INSERT INTO content (key, text_content) VALUES (?, ?)", (key, text))
            print(f"  + Inserted: {key}")
    conn.commit()
    conn.close()
    print("\nDone! All funnel content updated.")


if __name__ == "__main__":
    main()
